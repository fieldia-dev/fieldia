/** The app's answers to the head's buttons: Follow writes whether the bug is followed as the server keeps it, never a change to save. */
export function wiHeadAction(request: ActionRequest): ActionResult | undefined {
  if (request.action === 'follow') return { stored: { following: request.values['following'] !== true } };
  if (request.action === 'follow-all' || request.action === 'follow-state') return { stored: { following: true }, say: request.action === 'follow-all' ? 'Following every change' : 'Following state changes' };
  if (request.action === 'copy-link') return { say: 'Link copied' };
  return undefined;
}

